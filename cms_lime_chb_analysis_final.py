def assess_interpretability(explanation):
    """Assess if the explanation is interpretable based on average importance"""
    if not explanation.get('combined_explanation'):
        return False, 0.0
    
    combined = explanation['combined_explanation']
    selected_importances = combined.get('selected_importances', [])
    
    if not selected_importances:
        return False, 0.0
    
    avg_importance = np.mean([abs(imp) for imp in selected_importances])
    is_interpretable = avg_importance >= INTERPRETABILITY_THRESHOLD
    
    return is_interpretable, avg_importance

