class SimpleEEGModel(nn.Module):
    """Simple EEG model for fallback
    
    Designed for user's data format: (22, 1280) - 22 channels, 1280 timepoints
    """
    def __init__(self, n_channels=22, n_timepoints=1280, n_classes=2):
        super().__init__()
        self.conv1 = nn.Conv1d(n_channels, 64, kernel_size=7, padding=3)
        self.conv2 = nn.Conv1d(64, 128, kernel_size=5, padding=2)
        self.conv3 = nn.Conv1d(128, 256, kernel_size=3, padding=1)
        self.pool = nn.AdaptiveAvgPool1d(32)
        self.fc1 = nn.Linear(256 * 32, 512)
        self.fc2 = nn.Linear(512, n_classes)
        self.dropout = nn.Dropout(0.5)
        
        # Store model parameters
        self.n_channels = n_channels
        self.n_timepoints = n_timepoints
        self.n_classes = n_classes
        
    def forward(self, x):
        # x shape: (batch_size, channels, timepoints) or (channels, timepoints)
        if x.dim() == 2:
            # Add batch dimension if needed: (channels, timepoints) -> (1, channels, timepoints)
            x = x.unsqueeze(0)
        
        # Ensure correct input shape
        if x.shape[1] != self.n_channels or x.shape[2] != self.n_timepoints:
            raise ValueError(f"Expected input shape (batch, {self.n_channels}, {self.n_timepoints}), got {x.shape}")
        
        x = torch.relu(self.conv1(x))
        x = torch.relu(self.conv2(x))
        x = torch.relu(self.conv3(x))
        x = self.pool(x)
        x = self.dropout(x)
        x = x.view(x.size(0), -1)
        x = torch.relu(self.fc1(x))
        x = self.dropout(x)
        x = self.fc2(x)
        return torch.softmax(x, dim=1)

def load_model_robust(model_path, n_chans, n_classes=2, device='cpu'):
    """Robust model loading with proper EEGInception loading
    
    Args:
        model_path: Path to model weights file
        n_chans: Number of EEG channels (should be 22 for user's data)
        n_classes: Number of output classes
        device: Device to load model on
    
    Returns:
        Loaded model ready for inference
    """
    
    try:
        # Check if model path exists
        if not os.path.exists(model_path):
            raise FileNotFoundError(f"Model path not found: {model_path}")
        
        # Try to load EEGInception model
        log_print(f"Attempting to load EEGInception model with {n_chans} channels...")
        model = EEGInception(input_time=1280, fs=256, ncha=n_chans, n_classes=n_classes)
        
        # Load weights - handle different checkpoint formats
        try:
            checkpoint = torch.load(model_path, map_location=device)
            
            # Handle different checkpoint formats
            if isinstance(checkpoint, dict):
                if 'state_dict' in checkpoint:
                    state_dict = checkpoint['state_dict']
                elif 'model_state_dict' in checkpoint:
                    state_dict = checkpoint['model_state_dict']
                else:
                    state_dict = checkpoint
            else:
                state_dict = checkpoint
            
            # Load state dict with strict=False to handle minor mismatches
            model.load_state_dict(state_dict, strict=False)
            
        except Exception as load_error:
            log_print(f"Error loading checkpoint: {load_error}")
            log_print("Attempting to load as direct state dict...")
            
            # Try loading as direct state dict
            state_dict = torch.load(model_path, map_location=device)
            model.load_state_dict(state_dict, strict=False)
        
        model.to(device)
        model.eval()  # Set to evaluation mode
        
        log_print(f"Successfully loaded EEGInception model from {model_path}")
        return model
        
    except Exception as e:
        log_print(f"Error loading EEGInception model: {e}")
        log_print(f"Falling back to SimpleEEGModel with {n_chans} channels...")
        
        # Create simple model as fallback with correct channel count
        model = SimpleEEGModel(n_channels=n_chans, n_timepoints=1280, n_classes=n_classes)
        model.to(device)
        model.eval()
        
        log_print(f"Created SimpleEEGModel for demonstration (channels={n_chans}, timepoints=1280)")
        return model

